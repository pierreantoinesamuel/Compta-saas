/**
 * Authoritative PCG 2025 (Règlement ANC n° 2022-06 applicable au 1er janvier 2025)
 * Chart of Accounts & French/EU Tax Rules Catalog.
 *
 * Key PCG 2025 modernizations enforced:
 * - Abolition of account 79 ("Transferts de charges" is strictly forbidden in PCG 2025).
 * - Expense reimbursements use 649 / 708 / 758.
 * - Asset disposals ("Cessions d'immobilisations") use 657 / 757 instead of 675 / 775.
 * - Foreign exchange differences on commercial receivables/payables use 656 / 756.
 * - Exceptional accounts (67 / 77) are restricted strictly to major and unusual events.
 * - Collective accounts 411000 (Customers) and 401000 (Suppliers) require auxiliary codes (CompAuxNum).
 */

